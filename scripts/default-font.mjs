// Writes src/core/renderer/tvg/visDefaultFont.h: the font the engine registers as "default", as
// ThorVG's web players do, and sets text in when the font a text names is not loaded. It is the
// part of Pretendard Std that explanations use most (Latin, Greek, figures, arrows and math
// signs), without the layout tables ThorVG does not read, and without the font's names, as
// Pretendard's Reserved Font Name asks of a modified version; its copyright and license stay.
// Given Noto Sans Math, which the repository does not hold, it also writes visMathFont.h: the
// nine geometry symbols that text sets in it when its own font lacks them, with only the tables
// ThorVG reads and, likewise, its copyright and license.
// Needs hb-subset from HarfBuzz.
// Usage: node scripts/default-font.mjs [NotoSansMath-Regular.ttf]
import {execFileSync} from "node:child_process";
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from "node:fs";
import {tmpdir} from "node:os";
import {dirname, join, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fonts = join(root, "src/core/renderer/tvg");
const math = process.argv[2] ?? process.env.VIS_MATH_FONT;

const UNICODES = [
    "U+0020-007E", "U+00A0-017F",                                   // Latin, Latin-1, Latin Extended-A
    "U+0391-03A9", "U+03B1-03C9", "U+03D1", "U+03D5-03D6", "U+03F0-03F1", "U+03F5", // Greek, as math writes it
    "U+2013-2014", "U+2018-201E", "U+2020-2022", "U+2026", "U+2030", "U+2032-2033", "U+2039-203A", // punctuation
    "U+2070-209F",                                                  // superscripts and subscripts
    "U+20A9", "U+20AC", "U+2122",                                   // won, euro, trade mark
    "U+2190-2195", "U+21D0-21D4",                                   // arrows
    "U+2200-22FF", "U+25A0-25FF",                                   // math operators, shapes
];
// ∠ ° ⊥ ∥ △ ≅ ∼ π θ
const MATH_UNICODES = ["U+2220", "U+00B0", "U+22A5", "U+2225", "U+25B3", "U+2245", "U+223C", "U+03C0", "U+03B8"];
// The tables ThorVG reads, and the one that holds the copyright and license.
const KEPT = ["head", "hhea", "maxp", "cmap", "hmtx", "kern", "loca", "glyf", "CFF ", "name"];

function tables(font) {
    const view = new DataView(font.buffer, font.byteOffset, font.byteLength);
    const tables = new Map();
    for (let i = 0; i < view.getUint16(4); i++) {
        const record = 12 + i * 16;
        tables.set(font.toString("latin1", record, record + 4), {record, offset: view.getUint32(record + 8), length: view.getUint32(record + 12)});
    }
    return tables;
}

// The subset maps characters with format 4 alone, for which ThorVG takes a character the font
// lacks to glyph 0, keeping its advance. With none, that character is left out and measured as
// missing, as fonts with a format 12 map, which ThorVG reads first, leave it out.
function emptyNotdef(font) {
    const view = new DataView(font.buffer, font.byteOffset, font.byteLength);
    const word = (at) => at + 4 <= font.length ? view.getUint32(at) : font.subarray(at, at + 4).reduce((sum, byte, i) => sum + byte * 2 ** (24 - 8 * i), 0);
    const checksum = (offset, length) => {
        let sum = 0;
        for (let at = offset; at < offset + length; at += 4) sum = (sum + word(at)) >>> 0;
        return sum;
    };
    const found = tables(font);
    const hmtx = found.get("hmtx");
    const head = found.get("head");
    view.setUint32(hmtx.offset, 0);
    view.setUint32(head.offset + 8, 0);
    for (const table of [hmtx, head]) view.setUint32(table.record + 4, checksum(table.offset, table.length));
    view.setUint32(head.offset + 8, (0xb1b0afba - checksum(0, font.length)) >>> 0);
}

// Writes the part of source that options keep as the font NAME_FONT under the name given.
function embed(source, file, prefix, name, notice, options) {
    const output = join(fonts, file);
    const scratch = mkdtempSync(join(tmpdir(), "viscript-font-"));
    try {
        const subset = join(scratch, "subset.ttf");
        execFileSync("hb-subset", [source, ...options, `--output-file=${subset}`], {stdio: "inherit"});
        const bytes = readFileSync(subset);
        emptyNotdef(bytes);
        const rows = [];
        for (let at = 0; at < bytes.length; at += 20) {
            rows.push(`    ${[...bytes.subarray(at, at + 20)].map((byte) => `0x${byte.toString(16).padStart(2, "0")}`).join(", ")},`);
        }
        writeFileSync(output, `// Generated by scripts/default-font.mjs: ${notice}
#ifndef _VIS_${prefix}_FONT_H_
#define _VIS_${prefix}_FONT_H_

#include <cstdint>

static constexpr const char* ${prefix}_FONT_NAME = "${name}";
static constexpr uint8_t ${prefix}_FONT[] = {
${rows.join("\n")}
};

#endif
`);
        console.log(`${output}: ${bytes.length} bytes of font`);
    } finally {
        rmSync(scratch, {recursive: true, force: true});
    }
}

embed(join(root, "src/examples/assets/PretendardStd-Regular.ttf"), "visDefaultFont.h", "DEFAULT", "default",
      "part of Pretendard Std, SIL OFL 1.1; see\n// PretendardStd-OFL.txt.",
      [`--unicodes=${UNICODES.join(",")}`, "--drop-tables+=GSUB,GPOS,GDEF,DSIG", "--name-IDs=0,13,14"]);
if (math) {
    // Without the mirrored symbols and substitutes that shaping would add, which ThorVG never sets.
    const unread = [...tables(readFileSync(math)).keys()].filter((tag) => !KEPT.includes(tag));
    embed(math, "visMathFont.h", "MATH", "default math",
          "nine symbols of Noto Sans Math, SIL OFL 1.1;\n// see NotoSansMath-OFL.txt.",
          [`--unicodes=${MATH_UNICODES.join(",")}`, "--no-bidi-closure", "--no-layout-closure",
           `--drop-tables+=${unread.join(",")}`, "--name-IDs=0,13,14"]);
} else {
    console.log("visMathFont.h: left as it is; pass NotoSansMath-Regular.ttf to write it");
}
